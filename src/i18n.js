export const languageOptions = [
  { key: 'english', flag: 'assets/flags/us.svg', locale: 'en' },
  { key: 'czech', flag: 'assets/flags/cz.svg', locale: 'cs' },
  { key: 'german_standard', flag: 'assets/flags/de.svg', locale: 'de' },
  { key: 'portuguese_pt', flag: 'assets/flags/pt.svg', locale: 'pt-PT' },
  { key: 'spanish_standard', flag: 'assets/flags/es.svg', locale: 'es' },
  { key: 'italian_standard', flag: 'assets/flags/it.svg', locale: 'it' },
];

const locales = Object.fromEntries(languageOptions.map((language) => [language.key, language.locale]));

function format(template, values) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}

export function t(language, key, values = {}) {
  const pluralKey = Object.hasOwn(values, 'count')
    ? `${key}_${new Intl.PluralRules(locales[language] ?? 'en').select(values.count)}`
    : key;
  const message = messages[pluralKey] ?? messages[`${key}_other`] ?? messages[key];
  if (!message) throw new Error(`Unknown translation key: ${key}`);
  return format(message[language] ?? message.english, values);
}

export function topicKey(group) {
  return group.toLowerCase().replaceAll(' and ', '_and_').replaceAll(' ', '_');
}
